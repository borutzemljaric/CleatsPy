def Qd_element(cab, L, e, edot):
    """
    Compute internal damping force for a cable element.
    """

    # Damping coefficients
    #cab.a
    #cab.b


    # ---------- Main computation ----------
    # Ensure column vectors
    e = np.asarray(e).reshape(-1, 1)
    edot = np.asarray(edot).reshape(-1, 1)

    # Compute eps = (e' * b1(L) * e - 1)/2
    #B1 = b1(L)
    eps = (e.T @ b1(L) @ e - 1.0) / 2.0
    eps = eps.item()  # extract scalar

    # Compute Kl
    Kl = cab.EA * L * eps * Kl2(L)

    # Damping matrix combination
    M = M_element(cab.m, L)
    I1mat = I1(L)
    damping_matrix = cab.a * M + cab.b * cab.EI * L * I1mat + cab.b * Kl

    # Qd for one element in row
    Qd = damping_matrix @ edot

    return Qd.flatten()