def h_b2_matrike(k, L):
    k = np.asarray(k, dtype=float)
    n = k.size
    b2 = np.zeros((36, 36, n))

    for idx in range(n):
        ki = k[idx]
        t1 = 6*ki - 6*ki**2
        t2 = 3*ki**2 - 4*ki + 1
        t3 = 2*ki - 3*ki**2

        values = {
            'A': (t1*t1) / L**2,
            'B': (t1*t2) / L,
            'C':  t2*t2,
            'D': (t3*t1) / L,
            'E':  t3*t3,
            'F':  t3*t2,
        }

        for i in range(36):
            for j in range(36):
                cell = TEMPLATE[i][j]
                if cell == 0:
                    continue
                if cell.startswith('-'):
                    b2[i, j, idx] = -values[cell[1:]]
                else:
                    b2[i, j, idx] =  values[cell]

    return b2

